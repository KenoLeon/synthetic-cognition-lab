// v0.2 evaluation run: scene suite × orientations × masks, three estimators, scored against the
// identifiability labels. Writes eval/results.json and eval/summary.md; prints the summary.
//   node scripts/run_eval.mjs
import RAPIER from '@dimforge/rapier3d-compat';
import { mkdirSync, writeFileSync } from 'node:fs';
import { buildSuite, evaluate, runScene, SCENES, QUESTIONS, ESTIMATORS, nullEstimator, label } from '../src/eval.js';
import { buildObservation, validateObservation, MASKS } from '../src/observe.js';
import { spreadDownOrientations, angleDeg } from '../src/orient.js';

await RAPIER.init();
// Label set (planning/008): 'unified' (default) or 'v0.2-table' (original). Outputs are kept apart
// so the original v0.2 scores are never overwritten.
const labels = process.argv.includes('--labels=v0.2-table') ? 'v0.2-table' : 'unified';
const suffix = labels === 'unified' ? '-unified' : '';
const lines = [];
const out = (s = '') => { console.log(s); lines.push(s); };

// ---- build + leak checks ------------------------------------------------------------------
const t0 = Date.now();
const items = buildSuite(RAPIER, { orientations: 3 });
const schemaProblems = items.flatMap((it) => validateObservation(it.obs).map((p) => `${it.scene}/${it.orientation}/${it.mask}: ${p}`));

const audit = spreadDownOrientations(48);
let sum = 0;
for (const q of audit) {
  const run = runScene(RAPIER, SCENES[0], q, { settleSteps: 60, recordSteps: 60 });
  const ans = nullEstimator(buildObservation(run.steps, { mask: 'PSA' }), 'Q1');
  sum += angleDeg(ans.value, run.truth.apparentDown);
}
const constMean = sum / audit.length;

out(`# v0.2 evaluation summary (labels: ${labels})`);
out('');
out(`Generated by \`node scripts/run_eval.mjs\` (${((Date.now() - t0) / 1000).toFixed(1)} s for the suite and audit).`);
out(`Suite: ${SCENES.length} scenes × 3 seeded orientations × ${MASKS.length} masks = ${items.length} observations; ${QUESTIONS.length} questions; estimators: ${Object.keys(ESTIMATORS).join(', ')}.`);
out('');
out('## Leak audit');
out('');
out(`- Schema whitelist over all ${items.length} observations: ${schemaProblems.length ? `**FAIL**, ${schemaProblems.length} problems: ${schemaProblems.slice(0, 5).join('; ')}` : 'pass (no unexpected keys or values)'}.`);
out(`- Constant guess "down = body −y" over 48 orientations with evenly spread down directions: mean error ${constMean.toFixed(2)}° (pass band 90° ± 10°: ${Math.abs(constMean - 90) <= 10 ? 'pass' : '**FAIL**'}).`);

// ---- scoring ------------------------------------------------------------------------------
const rows = evaluate(items, labels);
const other = evaluate(items, labels === 'unified' ? 'v0.2-table' : 'unified');
mkdirSync('eval', { recursive: true });
writeFileSync(`eval/results${suffix}.json`, JSON.stringify({ generated: new Date().toISOString(), labels, rows }, null, 0));

const fmtErr = (q, v) => (v === null ? '—' : q === 'Q1' ? `${v.toFixed(2)}°` : `${(v * 100).toFixed(2)}%`);
out('');
out('## Scores (per estimator × mask × question)');
out('');
out('Correct = right answer, right "none", or correct abstention. Over-claim = answered where the label says not identifiable. Missed = abstained where identifiable. Mean error is over answered items with a defined truth (Q1 degrees, Q2/Q2b relative).');
for (const est of Object.keys(ESTIMATORS)) {
  out('');
  out(`### ${est}`);
  out('');
  out('| Mask | Q | n | Correct | Over-claims | Missed | Wrong | Mean error (answered) |');
  out('| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const mask of MASKS) for (const q of QUESTIONS) {
    const rs = rows.filter((r) => r.estimator === est && r.mask === mask && r.question === q);
    const errs = rs.filter((r) => r.error !== null).map((r) => r.error);
    const c = (o) => rs.filter((r) => r.outcome === o).length;
    out(`| ${mask} | ${q} | ${rs.length} | ${rs.filter((r) => r.correct).length} | ${c('over-claim')} | ${c('missed (abstained)')} | ${c('wrong')} | ${errs.length ? fmtErr(q, errs.reduce((a, b) => a + b, 0) / errs.length) : '—'} |`);
  }
}

// ---- disagreements between the analytic estimator and the table ----------------------------
out('');
out('## Analytic estimator: original v0.2 table vs. unified labels (contact-only prior)');
out('');
out('Only the cells that changed are listed.');
out('');
out('| Mask | Q | Correct, v0.2 table | Correct, unified |');
out('| --- | --- | --- | --- |');
const [v02Rows, uniRows] = labels === 'unified' ? [other, rows] : [rows, other];
const nOk = (rs, mask, q) => rs.filter((r) => r.estimator === 'analytic' && (!mask || r.mask === mask) && (!q || r.question === q) && r.correct).length;
for (const mask of MASKS) for (const q of QUESTIONS) {
  if (nOk(v02Rows, mask, q) !== nOk(uniRows, mask, q)) out(`| ${mask} | ${q} | ${nOk(v02Rows, mask, q)}/42 | ${nOk(uniRows, mask, q)}/42 |`);
}
out(`| **all** | | **${nOk(v02Rows)}/840** | **${nOk(uniRows)}/840** |`);
out('');
out(`## Analytic estimator vs. ${labels} labels: every disagreement`);
out('');
const dis = rows.filter((r) => r.estimator === 'analytic' && !r.correct);
const groups = new Map();
for (const r of dis) {
  const k = `${r.mask} ${r.question} — label ${r.label}, estimator ${r.answer} (${r.outcome})`;
  if (!groups.has(k)) groups.set(k, new Set());
  groups.get(k).add(r.scene);
}
if (!groups.size) out('None.');
for (const [k, scenes] of groups) out(`- ${k}: ${[...scenes].join(', ')}`);

writeFileSync(`eval/summary${suffix}.md`, lines.join('\n') + '\n');
console.log(`\nwrote eval/results${suffix}.json and eval/summary${suffix}.md (labels: ${labels})`);
