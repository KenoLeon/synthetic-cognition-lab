// Exploratory (report brief, 2026-10-23): within-item thinking comparison on the report set, to test the
// item-type confound on H3. For each item, its 4 replies (one per run) are split into replies with at least
// one over-claimed unanswerable answer and replies with none; items that have both kinds contribute one
// difference: mean thinking tokens (over-claim replies) − mean thinking tokens (clean replies). The item is
// held fixed, so item type cannot explain the difference. Wilcoxon signed-rank, one-sided (difference > 0),
// normal approximation. Writes aggregates only.
//   node scripts/llm_within_item.mjs   → eval/llm/report-set/within-item.md and .json
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { labelV2, labelQ1a, parseAnswer, scoreV2 } from '../src/llm.js';

const D = '../../private/gravity-from-touch/report-set', M = 'gemini-3.5-flash-lite', OUT = 'eval/llm/report-set';
const ids = readFileSync(`${D}/ids.txt`, 'utf8').split(/\r?\n/).filter(Boolean);
const diffs = []; let itemsMixed = 0, itemsAllOc = 0, itemsNoOc = 0, itemsNoUnanswerable = 0;
for (const id of ids) {
  const t = JSON.parse(readFileSync(`${D}/truth/${id}.json`, 'utf8'));
  const oc = [], clean = [];
  for (let k = 1; k <= 4; k++) {
    const p = `${D}/logs/${M}${k > 1 ? `-rep${k}` : ''}/${id}.json`;
    if (!existsSync(p)) continue;
    const log = JSON.parse(readFileSync(p, 'utf8'));
    if (log.httpStatus !== 200) continue;
    let raw; try { raw = JSON.parse(log.response.candidates[0].content.parts.filter((x) => !x.thought).map((x) => x.text).join('')); } catch { continue; }
    let un = 0, n = 0;
    for (const q of ['Q1a', 'Q2', 'Q2b', 'Q3', 'Q4']) {
      const lab = q === 'Q1a' ? labelQ1a(t.mask, t.truth) : labelV2(q, t.mask, t.truth);
      if (lab.kind !== 'not-identifiable') continue;
      un++; if (scoreV2(parseAnswer(q, raw), lab, t.truth).outcome === 'over-claim') n++;
    }
    if (!un) continue;
    (n ? oc : clean).push(log.response.usageMetadata?.thoughtsTokenCount ?? 0);
  }
  if (!oc.length && !clean.length) itemsNoUnanswerable++;
  else if (oc.length && clean.length) { itemsMixed++; diffs.push(oc.reduce((a, b) => a + b, 0) / oc.length - clean.reduce((a, b) => a + b, 0) / clean.length); }
  else if (oc.length) itemsAllOc++; else itemsNoOc++;
}

// Wilcoxon signed-rank (zeros dropped, average ranks for ties, normal approximation with tie correction).
const nz = diffs.filter((d) => d !== 0).map((d) => [Math.abs(d), Math.sign(d)]).sort((a, b) => a[0] - b[0]);
const N = nz.length, ranks = new Array(N); let tie = 0;
for (let i = 0; i < N;) { let j = i; while (j < N && nz[j][0] === nz[i][0]) j++; const tt = j - i; tie += tt ** 3 - tt; for (let k = i; k < j; k++) ranks[k] = (i + j + 1) / 2; i = j; }
const Wplus = nz.reduce((s, x, i) => s + (x[1] > 0 ? ranks[i] : 0), 0);
const mu = (N * (N + 1)) / 4, sigma = Math.sqrt((N * (N + 1) * (2 * N + 1)) / 24 - tie / 48), z = (Wplus - mu) / sigma;
const erf = (x) => { const t = 1 / (1 + 0.3275911 * x); return 1 - (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * Math.exp(-x * x); };
const p = z >= 0 ? 0.5 * (1 - erf(z / Math.SQRT2)) : 1 - 0.5 * (1 - erf(-z / Math.SQRT2));
const sorted = [...diffs].sort((a, b) => a - b), median = sorted.length ? (sorted.length % 2 ? sorted[(sorted.length - 1) / 2] : (sorted[sorted.length / 2 - 1] + sorted[sorted.length / 2]) / 2) : null;
const positive = diffs.filter((d) => d > 0).length, rRB = N ? (2 * Wplus) / ((N * (N + 1)) / 2) - 1 : null; // matched-pairs rank-biserial

const res = { items: ids.length, itemsMixed, itemsAllOverclaim: itemsAllOc, itemsNoOverclaim: itemsNoOc, itemsNoUnanswerable,
  medianDiffTokens: Math.round(median), positive, nonzero: N, z: Number(z.toFixed(2)), pOneSided: p, rankBiserial: Number(rRB.toFixed(2)) };
const md = `# Within-item thinking comparison (report set, exploratory)

Generated by \`node scripts/llm_within_item.mjs\`. Aggregates only. For each item, its four replies (one per run) are split into replies with at least one over-claimed unanswerable answer and replies with none; items with both kinds give one difference in mean thinking tokens. The item is held fixed, so item type cannot explain the difference.

- Items: ${res.items}; with both kinds of reply: ${res.itemsMixed}; over-claim in every run: ${res.itemsAllOverclaim}; never: ${res.itemsNoOverclaim}; no unanswerable answers: ${res.itemsNoUnanswerable}.
- Over-claim replies minus clean replies, same item: median ${res.medianDiffTokens} thinking tokens; positive in ${res.positive} of ${res.nonzero} items.
- Wilcoxon signed-rank, one-sided: z = ${res.z}, p ${p < 1e-6 ? '< 1e-6' : `= ${p.toFixed(4)}`}; matched-pairs rank-biserial r = ${res.rankBiserial}.
`;
writeFileSync(`${OUT}/within-item.md`, md);
writeFileSync(`${OUT}/within-item.json`, JSON.stringify(res, null, 1));
console.log(md);
