// Score the v0.2.1 runs (prompt v3: Q1 split into Q1a/Q1b; planning/008–009).
//   node scripts/llm_score_v3.mjs   → eval/llm/v3/score-v0.2.1.md and .json
// Q1a: scored against the net contact-force direction (squeeze reported separately).
// Q1b: reported in three buckets (009): vector (right / flipped / other), "cannot be determined"
//      (equivalence-aware; cross-checked against the same trial's Q4), "none" (zero-load vs loaded).
// Q2–Q4: scored as in v2 (labelV2), next to the v2 scores of the same trials.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { labelV2, labelQ1a, bucketQ1b, parseAnswer, scoreV2, classifyMiss, TAXONOMY, disclaimerFlags } from '../src/llm.js';
import { angleDeg } from '../src/orient.js';

// --dir=<folder>: score another run of the same items (snapshots, truth, id lists, logs/); default v0.2.1.
const D = process.argv.find((a) => a.startsWith('--dir='))?.slice(6) ?? 'eval/llm/v3';
const MAIN = 'gemini-3.5-flash-lite';
const SCORED = ['Q2', 'Q2b', 'Q3', 'Q4'];
const ids = (f) => readFileSync(`${D}/${f}`, 'utf8').split(String.fromCharCode(10)).map((x) => x.trim()).filter(Boolean);
const truthOf = (id) => JSON.parse(readFileSync(`${D}/truth/${id}.json`, 'utf8'));
function answerOf(dir, id) {
  const p = `${dir}/${id}.json`;
  if (!existsSync(p)) return null;
  const log = JSON.parse(readFileSync(p, 'utf8'));
  if (log.httpStatus !== 200) return null;
  const text = (log.response.candidates?.[0]?.content?.parts ?? []).filter((x) => !x.thought).map((x) => x.text).join('');
  try { return JSON.parse(text); } catch { return { _unparsed: text }; }
}
// v2 answers of the same trial (for side-by-side Q2–Q4).
const v2Answer = (id) => answerOf(`eval/llm/logs/${MAIN}`, id);

function scoreTrial(id, raw) {
  const t = truthOf(id), mask = t.mask, truth = t.truth;
  const out = { id, scene: t.scene, mask, raw };
  const a1a = parseAnswer('Q1a', raw);
  const l1a = labelQ1a(mask, truth);
  out.Q1a = { label: l1a.kind, ...scoreV2(a1a, l1a, truth) };
  if (l1a.kind === 'dir' && a1a.kind === 'dir') out.Q1a.errorDeg = angleDeg(a1a.value, l1a.value);
  if (l1a.kind === 'dir') out.Q1a.correct = a1a.kind === 'dir' && out.Q1a.errorDeg <= 2;
  out.Q1b = bucketQ1b(parseAnswer('Q1b', raw), truth, raw?.Q4);
  for (const q of SCORED) {
    const ans = parseAnswer(q, raw), lab = labelV2(q, mask, truth);
    const s = scoreV2(ans, lab, truth);
    out[q] = { label: lab.kind, ...s, category: classifyMiss(q, mask, ans, s.outcome, truth) };
  }
  return out;
}

const lines = [];
const o = (s = '') => { console.log(s); lines.push(s); };
const pct = (a, b) => (b ? `${a}/${b} (${Math.round((100 * a) / b)}%)` : '—');

// ---------------------------------------------------------------- Task 2: Q1 re-run
const task2 = ids('task2-ids.txt');
const rows = task2.map((id) => { const raw = answerOf(`${D}/logs/${MAIN}`, id); return raw ? scoreTrial(id, raw) : null; }).filter(Boolean);
o(`# v0.2.1 LLM results (prompt v3, ${MAIN})`);
o('');
o(`Generated by \`node scripts/llm_score_v3.mjs\`. Task 2: ${rows.length}/${task2.length} touch trials answered.`);
o('');
o('## Q1a: which way the surfaces push you (scored against the net contact-force direction)');
o('');
o('| Sense set | Answerable direction: within 2° | Mean error (answered) | "none" correct (no contact) | Squeeze (no single direction) | Pressure only: abstained correctly |');
o('| --- | --- | --- | --- | --- | --- |');
for (const mask of ['P', 'PS', 'PSA']) {
  const rs = rows.filter((r) => r.mask === mask);
  const dir = rs.filter((r) => r.Q1a.label === 'dir');
  const errs = dir.map((r) => r.Q1a.errorDeg).filter((e) => e != null);
  const noContact = rs.filter((r) => r.Q1a.label === 'none' && r.scene !== 'squeeze');
  const sq = rs.filter((r) => r.scene === 'squeeze');
  const sqAns = sq.map((r) => JSON.stringify(r.raw.Q1a)).join(', ');
  const ni = rs.filter((r) => r.Q1a.label === 'not-identifiable');
  o(`| ${mask} | ${dir.length ? pct(dir.filter((r) => r.Q1a.correct).length, dir.length) : '—'} | ${errs.length ? `${(errs.reduce((a, b) => a + b, 0) / errs.length).toFixed(1)}°` : '—'} | ${pct(noContact.filter((r) => r.Q1a.correct).length, noContact.length)} | ${sq.length ? sqAns : '—'} | ${ni.length ? pct(ni.filter((r) => r.Q1a.correct).length, ni.length) : '—'} |`);
}

o('');
o('## Q1b: which way, if any, you are being pulled (three buckets, planning/009)');
o('');
o('| Sense set | Trials | Vector: right (≤ 2° of apparent down) | Vector: flipped (≤ 10° of opposite) | Vector: other | "Cannot be determined" (consistent with Q4 / says "gravity" on Q4) | "None": zero-load scenes / loaded scenes |');
o('| --- | --- | --- | --- | --- | --- | --- |');
for (const mask of ['P', 'PS', 'PSA']) {
  const b = rows.filter((r) => r.mask === mask).map((r) => r.Q1b);
  const n = (f) => b.filter(f).length;
  o(`| ${mask} | ${b.length} | ${n((x) => x.verdict === 'right')} | ${n((x) => x.verdict === 'flipped')} | ${n((x) => x.bucket === 'vector' && !['right', 'flipped'].includes(x.verdict))} | ${n((x) => x.bucket === 'cannot' && x.consistentWithQ4)} / ${n((x) => x.bucket === 'cannot' && !x.consistentWithQ4)} | ${n((x) => x.bucket === 'none' && x.zeroLoad)} / ${n((x) => x.bucket === 'none' && !x.zeroLoad)} |`);
}
const readRight = rows.filter((r) => r.Q1a.label === 'dir' && r.Q1a.correct);
const readRightVec = readRight.filter((r) => r.Q1b.bucket === 'vector');
o('');
o(`**Right reading, flipped interpretation:** of the ${readRight.length} trials where Q1a was right (within 2°), Q1b gave a vector in ${readRightVec.length}; of those, ${readRightVec.filter((r) => r.Q1b.verdict === 'flipped').length} were flipped (pulled the same way as pushed) and ${readRightVec.filter((r) => r.Q1b.verdict === 'right').length} pointed to apparent down. ${readRight.filter((r) => r.Q1b.bucket === 'cannot').length} answered "cannot be determined" and ${readRight.filter((r) => r.Q1b.bucket === 'none').length} "none".`);

o('');
o('## Q2–Q4 on the same trials: v2 prompt vs. v3 prompt');
o('');
o('| Q | v2 correct | v3 correct | v2 over-claims | v3 over-claims |');
o('| --- | --- | --- | --- | --- |');
for (const q of SCORED) {
  let v2c = 0, v2o = 0, n = 0;
  for (const r of rows) {
    const raw2 = v2Answer(r.id); if (!raw2) continue; n++;
    const t = truthOf(r.id); const s = scoreV2(parseAnswer(q, raw2), labelV2(q, r.mask, t.truth), t.truth);
    if (s.correct) v2c++; if (s.outcome === 'over-claim') v2o++;
  }
  o(`| ${q} | ${pct(v2c, n)} | ${pct(rows.filter((r) => r[q].correct).length, rows.length)} | ${v2o} | ${rows.filter((r) => r[q].outcome === 'over-claim').length} |`);
}
{
  // Q2 asks "how strong is THAT pull or press": its referent changed when Q1 became Q1a/Q1b. Where
  // Q1b says "cannot be determined" (defensible everywhere, 009), Q2 "cannot be determined" follows.
  const coupled = rows.filter((r) => r.Q2.outcome !== 'correct zero' && !r.Q2.correct && parseAnswer('Q2', r.raw).kind === 'abstain' && r.Q1b.bucket === 'cannot');
  o('');
  o(`**Q2 coupling to Q1b.** Q2 asks "how strong is *that* pull or press"; in v3 "that" can refer to Q1b's pull. In ${coupled.length} trials Q2 answered "cannot be determined" where the strict label expects 0, and the same trial's Q1b was also "cannot be determined": consistent, and defensible (free fall: gravity pulls, but can't be sensed). Q2 counting those as correct: ${pct(rows.filter((r) => r.Q2.correct).length + coupled.length, rows.length)}. The v2/v3 Q2 comparison is therefore not like-for-like.`);
}
o('');
o('## Taxonomy of misses, Q2–Q4 (v3 run)');
o('');
o('| Category | Count |');
o('| --- | --- |');
const cats = {};
for (const r of rows) for (const q of SCORED) if (r[q].category) cats[r[q].category] = (cats[r[q].category] ?? 0) + 1;
for (const k of Object.keys(TAXONOMY)) if (cats[k]) o(`| ${k} | ${cats[k]} |`);

// ---------------------------------------------------------------- Task 3: stability
const stab = ids('stability-ids.txt');
const runDir = (k) => `${D}/logs/${MAIN}${k > 1 ? `-rep${k}` : ''}`;
const same = (q, a, b) => {
  const x = parseAnswer(q, a), y = parseAnswer(q, b);
  if (x.kind !== y.kind) return false;
  if (x.kind === 'dir') return angleDeg(x.value, y.value) <= 2;
  if (x.kind === 'mag') return Math.abs(x.value - y.value) <= 0.01 * Math.max(Math.abs(x.value), Math.abs(y.value), 1e-9);
  if (x.kind === 'cat') return x.value === y.value;
  return true;
};
const QS = ['Q1a', 'Q1b', ...SCORED];
const runs = [1, 2, 3].map((k) => stab.map((id) => ({ id, raw: answerOf(runDir(k), id) })));
const complete = stab.filter((_, i) => runs.every((rr) => rr[i].raw));
o('');
o('## Stability: 24 items × 3 runs (Task 3)');
o('');
o(`Items with all 3 runs answered: ${complete.length}/${stab.length}. Agreement = all three answers the same (directions within 2°, numbers within 1%, same category).`);
o('');
o('| Question | Items with identical answers in all 3 runs |');
o('| --- | --- |');
for (const q of QS) {
  const agree = complete.filter((id) => { const a = runs.map((rr) => rr.find((x) => x.id === id).raw); return same(q, a[0], a[1]) && same(q, a[0], a[2]); }).length;
  o(`| ${q} | ${pct(agree, complete.length)} |`);
}
const ocRates = runs.map((rr) => {
  let oc = 0, n = 0;
  for (const { id, raw } of rr) {
    if (!raw || !complete.includes(id)) continue;
    const s = scoreTrial(id, raw);
    for (const q of SCORED) { n++; if (s[q].outcome === 'over-claim') oc++; }
  }
  return n ? oc / n : null;
});
const okRates = ocRates.filter((x) => x !== null);
const mean = okRates.reduce((a, b) => a + b, 0) / okRates.length;
const sd = Math.sqrt(okRates.reduce((a, b) => a + (b - mean) ** 2, 0) / okRates.length);
o('');
o(`Over-claim rate on Q2–Q4 per run: ${okRates.map((x) => `${(100 * x).toFixed(1)}%`).join(', ')}; mean ${(100 * mean).toFixed(1)}%, spread ±${(100 * sd).toFixed(1)} points (SD), range ${(100 * Math.min(...okRates)).toFixed(1)}–${(100 * Math.max(...okRates)).toFixed(1)}%.`);

// ---------------------------------------------------------------- Task 4: Flash spot check
const flashIds = ids('flash-ids.txt');
const flash = flashIds.map((id) => { const raw = answerOf(`${D}/logs/gemini-3.8-flash`, id); return raw ? scoreTrial(id, raw) : null; }).filter(Boolean);
o('');
o('## Flash spot check (Task 4, optional)');
o('');
if (!flash.length) o('Not run (or no successful answers yet).');
else {
  const lite = flash.map((f) => scoreTrial(f.id, answerOf(runDir(1), f.id)));
  const oc = (rs) => rs.reduce((a, r) => a + SCORED.filter((q) => r[q].outcome === 'over-claim').length, 0);
  const dirOk = (rs) => rs.filter((r) => r.Q1a.label === 'dir' && r.Q1a.correct).length;
  const flip = (rs) => rs.filter((r) => r.Q1b.verdict === 'flipped').length;
  const cant = (rs) => rs.filter((r) => r.Q1b.bucket === 'cannot').length;
  o(`gemini-3.8-flash on ${flash.length} of the stability items, next to Flash Lite's run 1 on the same items:`);
  o('');
  o('| Model | Q1a right (answerable) | Q1b flipped | Q1b "cannot be determined" | Over-claims on Q2–Q4 |');
  o('| --- | --- | --- | --- | --- |');
  const nDir = flash.filter((r) => r.Q1a.label === 'dir').length;
  o(`| gemini-3.8-flash | ${dirOk(flash)}/${nDir} | ${flip(flash)} | ${cant(flash)} | ${oc(flash)}/${flash.length * SCORED.length} |`);
  o(`| gemini-3.5-flash-lite | ${dirOk(lite)}/${nDir} | ${flip(lite)} | ${cant(lite)} | ${oc(lite)}/${lite.length * SCORED.length} |`);
}

// ---------------------------------------------------------------- performance (measured latency)
const L = readdirSync(`${D}/logs/${MAIN}`).map((f) => JSON.parse(readFileSync(`${D}/logs/${MAIN}/${f}`, 'utf8'))).filter((l) => l.httpStatus === 200);
const lat = L.filter((l) => typeof l.latencyMs === 'number').map((l) => l.latencyMs / 1000).sort((a, b) => a - b);
const th = L.map((l) => l.response.usageMetadata?.thoughtsTokenCount ?? 0).sort((a, b) => a - b);
const q = (a, p) => a[Math.floor(p * (a.length - 1))];
o('');
o('## Performance (run 1, measured)');
o('');
if (lat.length) o(`Response time over ${lat.length} requests: median ${q(lat, 0.5).toFixed(1)} s, p10 ${q(lat, 0.1).toFixed(1)} s, p90 ${q(lat, 0.9).toFixed(1)} s, max ${lat.at(-1).toFixed(1)} s. Thinking tokens: median ${q(th, 0.5)}, max ${th.at(-1)}.`);

// ---------------------------------------------------------------- refusals and disclaimers (README.md, The rules, rule 5)
// Their own category: a refusal answer is neither an abstention nor a wrong answer. Trial-level
// AI disclaimers and frame breaks are counted from the whole reply and do not change any score.
const refusalRuns = [
  ['run 1', runDir(1), [...task2, ...ids('stability-A-ids.txt')]], ['run 2', runDir(2), stab], ['run 3', runDir(3), stab],
  ['gemini-3.8-flash', `${D}/logs/gemini-3.8-flash`, flashIds],
].map(([name, dir, list]) => {
  const c = { name, replies: 0, refusalAnswers: 0, aiDisclaimer: 0, frameBreak: 0, refusalReply: 0 };
  for (const id of list) {
    const raw = answerOf(dir, id);
    if (!raw) continue;
    c.replies++;
    for (const q of ['Q1a', 'Q1b', ...SCORED]) if (parseAnswer(q, raw).kind === 'refusal') c.refusalAnswers++;
    const f = disclaimerFlags(raw._unparsed ?? JSON.stringify(raw));
    if (f.aiDisclaimer) c.aiDisclaimer++;
    if (f.frameBreak) c.frameBreak++;
    if (f.refusal) c.refusalReply++;
  }
  return c;
});
o('');
o('## Refusals and disclaimers (LAB.md rule 5)');
o('');
o('Scored as their own category, never as abstention or failure. Refusal answers: answer fields that decline the task (6 per reply: Q1a, Q1b, Q2–Q4). Trial-level flags from the whole reply: refusal wording anywhere, an AI disclaimer ("as an AI", "I don\'t have a body"), a frame break ("simulation", "hypothetical", "role-play").');
o('');
o('| Run | Replies | Refusal answers | Replies with refusal wording | AI disclaimer | Frame break |');
o('| --- | --- | --- | --- | --- | --- |');
for (const c of refusalRuns) o(`| ${c.name} | ${c.replies} | ${c.refusalAnswers} | ${c.refusalReply} | ${c.aiDisclaimer} | ${c.frameBreak} |`);

writeFileSync(`${D}/score-v0.2.1.md`, lines.join('\n') + '\n');
writeFileSync(`${D}/score-v0.2.1.json`, JSON.stringify({ task2: rows, flash, refusalsAndDisclaimers: refusalRuns }, null, 0));
console.log(`\nwrote ${D}/score-v0.2.1.md`);
