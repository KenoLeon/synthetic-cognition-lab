// Report set: over-claim per unanswerable question (pre-announcement brief, 2026-10-28). EXPLORATORY, not
// pre-registered. Same parser, labels and scorer as scripts/llm_report_set.mjs; writes AGGREGATES ONLY.
// Unanswerable answers are those labeled "not-identifiable" on Q1a, Q2, Q2b, Q3, Q4 (as in the report);
// Q1b is bucketed, not scored right/wrong (src/llm.js, bucketQ1b), so it is not part of the 28.2%.
//   node scripts/llm_report_set_by_question.mjs [--items=<folder>] [--logs=<folder>] [--out=<folder>]
//   defaults: the local report set (../../private/gravity-from-touch/report-set, items and logs in one folder);
//   the released bundle is --items=<release>/items --logs=<release>/logs
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { labelV2, labelQ1a, parseAnswer, scoreV2 } from '../src/llm.js';

const arg = (k, d) => process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3) ?? d;
const ITEMS = arg('items', '../../private/gravity-from-touch/report-set'), LOGS = arg('logs', `${ITEMS}/logs`);
const OUT = arg('out', 'eval/llm/report-set'), RUNS = Number(arg('runs', '4'));
const M = 'gemini-3.5-flash-lite', QS = ['Q1a', 'Q2', 'Q2b', 'Q3', 'Q4'];
const lines = (p) => readFileSync(p, 'utf8').split(/\r?\n/).map((x) => x.trim()).filter(Boolean);
const IDS = lines(`${ITEMS}/ids.txt`);
const runDir = (k) => `${LOGS}/${M}${k > 1 ? `-rep${k}` : ''}`;
const truthOf = (id) => JSON.parse(readFileSync(`${ITEMS}/truth/${id}.json`, 'utf8'));

const un = []; // unanswerable answers: { run, q, scene, oc }
for (let k = 1; k <= RUNS; k++) {
  for (const id of IDS) {
    const p = `${runDir(k)}/${id}.json`;
    if (!existsSync(p)) continue;
    const log = JSON.parse(readFileSync(p, 'utf8'));
    if (log.httpStatus !== 200) continue;
    const text = (log.response.candidates?.[0]?.content?.parts ?? []).filter((x) => !x.thought).map((x) => x.text).join('');
    let raw; try { raw = JSON.parse(text); } catch { raw = { _unparsed: text }; }
    const t = truthOf(id);
    for (const q of QS) {
      const lab = q === 'Q1a' ? labelQ1a(t.mask, t.truth) : labelV2(q, t.mask, t.truth);
      if (lab.kind !== 'not-identifiable') continue;
      const s = scoreV2(parseAnswer(q, raw), lab, t.truth);
      un.push({ run: k, q, scene: t.scene, oc: s.outcome === 'over-claim' });
    }
  }
}

const wilson = (x, n, z = 1.96) => {
  if (!n) return [null, null];
  const p = x / n, d = 1 + (z * z) / n, c = (p + (z * z) / (2 * n)) / d, h = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [c - h, c + h];
};
const pct = (x) => (x === null ? '—' : `${(100 * x).toFixed(1)}%`);
const tally = (rows) => { const x = rows.filter((a) => a.oc).length, n = rows.length; return { x, n, rate: n ? x / n : null, ci: wilson(x, n) }; };

const total = tally(un);
const byQ = Object.fromEntries(QS.map((q) => [q, tally(un.filter((a) => a.q === q))]));
const sumX = QS.reduce((s, q) => s + byQ[q].x, 0), sumN = QS.reduce((s, q) => s + byQ[q].n, 0);
const scenes = [...new Set(un.map((a) => a.scene))].sort();
const grid = Object.fromEntries(scenes.map((s) => [s, Object.fromEntries(QS.map((q) => [q, tally(un.filter((a) => a.scene === s && a.q === q))]))]));
const byRun = Object.fromEntries(QS.map((q) => [q, [...Array(RUNS)].map((_, i) => tally(un.filter((a) => a.q === q && a.run === i + 1)))]));

const o = [];
o.push('# Gravity from Touch — report set, over-claim by question (exploratory)', '');
o.push(`Generated by \`node scripts/llm_report_set_by_question.mjs\` (2026-10-28). **Exploratory: not pre-registered.** Aggregates only, from the report-set logs as released with the report (doi:10.5281/zenodo.23654739). Same scorer as \`summary.md\`. ${RUNS} runs pooled; Wilson 95% CI. Q1b is not scored right/wrong (bucketed), so it is not part of the over-claim rate; Q1a counts only where its push direction can't be told: slide readings switched off (sense set P) or no touch (set A).`, '');
o.push('## Over-claim per unanswerable question', '');
o.push('| Question | Over-claims | Rate | 95% CI | Share of all over-claims |', '| --- | --- | --- | --- | --- |');
for (const q of QS) { const t = byQ[q]; o.push(`| ${q} | ${t.x}/${t.n} | ${pct(t.rate)} | ${pct(t.ci[0])}–${pct(t.ci[1])} | ${pct(total.x ? t.x / total.x : null)} |`); }
o.push(`| **All** | **${total.x}/${total.n}** | **${pct(total.rate)}** | ${pct(total.ci[0])}–${pct(total.ci[1])} | 100% |`);
o.push('', `Check: per-question counts sum to ${sumX}/${sumN} (report: 528/1872) → **${sumX === 528 && sumN === 1872 ? 'match' : 'MISMATCH'}**.`, '');
o.push('Per run (over-claims/unanswerable):', '', `| Question | ${[...Array(RUNS)].map((_, i) => `run ${i + 1}`).join(' | ')} |`, `| --- |${' --- |'.repeat(RUNS)}`);
for (const q of QS) o.push(`| ${q} | ${byRun[q].map((t) => `${t.x}/${t.n}`).join(' | ')} |`);
o.push('', '## Question × scene (over-claims/unanswerable, 4 runs pooled; — = answerable there)', '');
o.push(`| Scene | ${QS.join(' | ')} | All |`, `| --- |${' --- |'.repeat(QS.length + 1)}`);
for (const s of scenes) {
  const all = tally(un.filter((a) => a.scene === s));
  o.push(`| ${s} | ${QS.map((q) => (grid[s][q].n ? `${grid[s][q].x}/${grid[s][q].n} (${pct(grid[s][q].rate)})` : '—')).join(' | ')} | ${all.x}/${all.n} (${pct(all.rate)}) |`);
}

mkdirSync(OUT, { recursive: true });
writeFileSync(`${OUT}/by-question.md`, o.join('\n') + '\n');
writeFileSync(`${OUT}/by-question.json`, JSON.stringify({ exploratory: true, total, byQuestion: byQ, byRun, byScene: grid, sumCheck: { x: sumX, n: sumN } }, null, 1));
console.log(o.join('\n'));
