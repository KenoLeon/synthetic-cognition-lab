// Bundle logged episodes for the static replay page (replay/index.html). Logged data only: each episode exactly as
// logged (system prompt, task, every model turn and tool result, notice, final world state) plus its score from
// src/score.js. Refuses anything under private/ (the report set never goes on a page while in use).
//   node scripts/build_replay.mjs [--dir=runs/mock-tuning] [--out=replay/data/episodes.js] [--label="..."] [--commit=<runs-branch commit>]
// Thought signatures (opaque provider blobs in each model turn's raw parts) are left out: they are not readable and
// only needed to resend a turn; every readable field (text, thought summary, calls, results) is kept as logged.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { scoreEpisode } from '../src/score.js';

const arg = (k, d) => { const a = process.argv.find((x) => x.startsWith(`--${k}=`)); return a ? a.slice(k.length + 3) : d; };
const dir = arg('dir', 'runs/mock-tuning'), out = arg('out', 'replay/data/episodes.js');
if (/[\\/]private([\\/]|$)/.test(resolve(dir)) || /(^|[\\/])private[\\/]/.test(dir)) { console.error('refusing to bundle logs from private/'); process.exit(1); }

const eps = readdirSync(`${dir}/raw`).filter((f) => f.endsWith('.json')).sort().map((f) => {
  const ep = JSON.parse(readFileSync(`${dir}/raw/${f}`, 'utf8'));
  const slim = (t) => (t && t.turn ? { ...t, turn: { ...t.turn, raw: undefined } } : t);
  return { ...ep, historyTurns: (ep.historyTurns ?? []).map(slim), branchPoint: ep.branchPoint ? slim(ep.branchPoint) : null, branchTurns: (ep.branchTurns ?? []).map(slim), score: scoreEpisode(ep) };
});
const source = arg('source', dir); // a public description of where the logs came from (default: --dir)
const meta = { source, builtAt: new Date().toISOString(), episodes: eps.length, mock: eps.every((e) => e.adapter?.name === 'mock'), label: arg('label', null), commit: arg('commit', null) };
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/build_replay.mjs from ${source}. Logged data only.\nwindow.SAT_REPLAY = ${JSON.stringify({ meta, episodes: eps })};\n`);
console.log(`${eps.length} episodes → ${out} (${(readFileSync(out).length / 1024).toFixed(0)} KB)${meta.mock ? ' [mock data]' : ''}`);
